#!/usr/bin/env python3
"""Derives NOAA opengeo's reflectivity color -> dBZ table (Shared/RadarPaletteTable.swift).

opengeo's conus_bref_qcd layer is pre-colored (its SLD has no ColorMap), so the dBZ behind each
color isn't published. nowCOAST serves the same MRMS mosaic (conus_base_reflectivity_mosaic) with
a published ColorMap. Fetch both for the same EPSG:3857 BBOX, size and TIME, then:

    python3 -I tools/derive-radar-palette.py nowcoast-legend.json \\
        opengeo1.png:nowcoast1.png [opengeo2.png:nowcoast2.png ...] [more-opengeo.png ...] \
        > Shared/RadarPaletteTable.swift

Arguments without a nowCOAST partner only add colors to the palette (for colors that are rare
on the paired days).

nowcoast-legend.json is GetLegendGraphic with format=application/json for that layer.
Needs Pillow. Method:
1. Every opaque opengeo color is paired with the dBZ of the nowCOAST pixel under it (nowCOAST
   colors inverted through its ColorMap ramp). The median per color is the measured dBZ;
   nowCOAST floors to whole dBZ, so add 0.5.
2. Colors are ordered along the ramp by walking nearest neighbors from the faint (mauve) end;
   the yellow-orange-red run (R=255, B=0) is ordered by decreasing green.
3. Well-sampled colors (MIN_SAMPLES) are anchors, made non-decreasing along the ramp; other colors
   are interpolated by position between anchors, and extrapolated beyond them at 0.5 dBZ per
   step (the ramp's step, measured where samples are dense).
"""
import json
import math
import statistics
import sys
from collections import defaultdict

from PIL import Image

MIN_SAMPLES = 100
STEP_DBZ = 0.5
FAINT_END = (135, 116, 139)


def nowcoast_ramp(legend_path):
    entries = json.load(open(legend_path))["Legend"][0]["rules"][0]["symbolizers"][0]["Raster"]["colormap"]["entries"]
    anchors = []
    for entry in entries:
        if entry["label"] == "nodata":
            continue
        hex_color = entry["color"].lstrip("#")
        anchors.append((float(entry["quantity"]), tuple(int(hex_color[i:i + 2], 16) for i in (0, 2, 4))))
    dense = []
    for (q0, c0), (q1, c1) in zip(anchors, anchors[1:]):
        n = max(1, int((q1 - q0) * 10))
        for k in range(n):
            t = k / n
            dense.append((q0 + (q1 - q0) * t, tuple(c0[i] + (c1[i] - c0[i]) * t for i in range(3))))
    dense.append(anchors[-1])
    return dense


def main(legend_path, pairs):
    dense = nowcoast_ramp(legend_path)
    inverse = {}

    def nowcoast_dbz(rgb):
        if rgb not in inverse:
            inverse[rgb] = min(dense, key=lambda d: math.dist(d[1], rgb))[0]
        return inverse[rgb]

    samples = defaultdict(list)
    for pair in pairs:
        if ":" not in pair:
            for a in Image.open(pair).convert("RGBA").get_flattened_data():
                if a[3] == 255:
                    samples[a[:3]]
            continue
        opengeo_path, nowcoast_path = pair.split(":")
        og = Image.open(opengeo_path).convert("RGBA")
        nc = Image.open(nowcoast_path).convert("RGBA")
        assert og.size == nc.size, pair
        for a, b in zip(og.get_flattened_data(), nc.get_flattened_data()):
            if a[3] == 255:
                samples[a[:3]]  # every opaque color is part of the palette
                if b[3] > 0:
                    samples[a[:3]].append(nowcoast_dbz(b[:3]))

    colors = set(samples)
    order = [FAINT_END]
    rest = colors - {FAINT_END}
    while rest:
        nxt = min(rest, key=lambda c: math.dist(c, order[-1]))
        order.append(nxt)
        rest.remove(nxt)
    hot = [c for c in order if c[0] == 255 and c[2] == 0]
    first_hot = order.index(hot[0])
    order = [c for c in order if c not in hot]
    order[first_hot:first_hot] = sorted(hot, key=lambda c: -c[1])

    anchors = {}
    floor = -math.inf
    for i, color in enumerate(order):
        values = samples[color]
        if len(values) >= MIN_SAMPLES:
            floor = max(floor, statistics.median(values) + 0.5)
            anchors[i] = floor
    indices = sorted(anchors)
    dbz = []
    for i in range(len(order)):
        if i in anchors:
            dbz.append(anchors[i])
        elif i < indices[0]:
            dbz.append(anchors[indices[0]] - (indices[0] - i) * STEP_DBZ)
        elif i > indices[-1]:
            dbz.append(anchors[indices[-1]] + (i - indices[-1]) * STEP_DBZ)
        else:
            lo = max(j for j in indices if j < i)
            hi = min(j for j in indices if j > i)
            dbz.append(anchors[lo] + (anchors[hi] - anchors[lo]) * (i - lo) / (hi - lo))

    print("// Generated by tools/derive-radar-palette.py, which describes the method.")
    print("// NOAA opengeo conus_bref_qcd colors in ramp order, with their reflectivity in dBZ.")
    print("// `measured` is the number of paired nowCOAST pixels behind the value; colors with fewer")
    print(f"// than {MIN_SAMPLES} were interpolated or extrapolated.")
    print()
    print("extension RadarPalette {")
    print("    static let noaaTable: [(r: UInt8, g: UInt8, b: UInt8, dbz: Double, measured: Int)] = [")
    for color, value in zip(order, dbz):
        print(f"        ({color[0]}, {color[1]}, {color[2]}, {value:.1f}, {len(samples[color])}),")
    print("    ]")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
